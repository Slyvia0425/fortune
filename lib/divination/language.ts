export function divinationText(locale: Locale, text: string): string {
  if(locale!=="en")return text;
  const relation=text.match(/^([金木水火土])(生|克)([金木水火土])$/);
  if(relation)return `${DIVINATION_EN[relation[1]]} ${relation[2]==="生"?"generates":"controls"} ${DIVINATION_EN[relation[3]]}`;
  const same=text.match(/^([金木水火土])气相承$/);
  if(same)return `Shared ${DIVINATION_EN[same[1]]} element`;
  return DIVINATION_EN[text] ?? translate(locale, text);
}
