/** Numbers and acknowledgements do not change the language of a question. */
export function questionLanguage(messages: DivinationChatMessage[], fallback: Locale = "zh"): Locale {
  let language = fallback;
  let explicit: Locale | undefined;
  for (const { role, content } of messages) {
    if (role !== "user") continue;
    if (/(?:用|使用|改成|切换到)\s*英文|(?:reply|respond|answer|explain|translate).*\b(?:in|into) English\b/i.test(content)) explicit = "en";
    else if (/(?:用|使用|改成|切换到)\s*中文|(?:reply|respond|answer|explain|translate).*\b(?:in|into) Chinese\b/i.test(content)) explicit = "zh";
    const han = (content.match(/\p{Script=Han}/gu) ?? []).length;
    const words = (content.match(/[a-zA-Z]+/g) ?? []).length;
    if (han >= 1 || (words >= 1 && !/^(?:ok(?:ay)?|yes|no|thanks?|sure|please|numbers?)[.!\s]*$/i.test(content.trim()))) language = han >= words ? "zh" : "en";
  }
  return explicit ?? language;
}

